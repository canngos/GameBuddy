export const countryNames: Record<Exclude<Lang, 'en'>, Localized> = { tr, de, es, fr, fi, sv };

/**
 * The display name for a stored country value.
 *
 * Falls back to the raw value: the server column is varchar, so a profile written
 * before the picker existed can hold anything, and an unknown value must render as
 * itself rather than crash or blank.
 */
export function countryName(name: string, lang: Lang): string {
  if (lang === 'en') return name;
  return (countryNames[lang] as Record<string, string>)[name] ?? name;
}

/**
 * `countryName` bound to the language currently in force. Identity-stable per
 * language, so it is safe in `useMemo`/`useCallback` dependency lists.
 */
export function useCountryName(): (name: string | null | undefined) => string {
  const lang = useLangStore((s) => s.lang);
  return useCallback((name: string | null | undefined) => (name ? countryName(name, lang) : ''), [
    lang,
  ]);
}
